"""Export the consultation package as the root module used in submission ZIPs."""

import argparse
import ast
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
MODULES = ("models", "knowledge_base", "search", "agent", "cli")
OUTPUT = ROOT / "energytool_rag.py"


def build_source():
    imports = {}
    sections = []
    for module in MODULES:
        path = ROOT / "consultation_agent" / f"{module}.py"
        source = path.read_text(encoding="utf-8")
        tree = ast.parse(source, filename=str(path))
        nodes = tree.body
        header_end = 0
        if ast.get_docstring(tree) is not None:
            header_end = nodes[0].end_lineno
            nodes = nodes[1:]
        for node in nodes:
            if not isinstance(node, (ast.Import, ast.ImportFrom)):
                break
            header_end = node.end_lineno
            if not isinstance(node, ast.ImportFrom) or not node.level:
                statement = ast.get_source_segment(source, node)
                imports.setdefault(statement, None)
        sections.append("".join(source.splitlines(keepends=True)[header_end:]).strip())
    header = '"""Standalone consultation module for the submission ZIP."""\n'
    header += "# Generated by scripts/export_consultation.py from consultation_agent/.\n"
    return header + "\n" + "\n".join(imports) + "\n\n\n" + "\n\n\n".join(sections) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify the generated module is current.")
    args = parser.parse_args()
    source = build_source()
    compile(source, OUTPUT.name, "exec")
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != source:
            parser.exit(1, "Run python scripts/export_consultation.py to refresh energytool_rag.py.\n")
    else:
        with OUTPUT.open("w", encoding="utf-8", newline="\n") as file:
            file.write(source)


if __name__ == "__main__":
    main()
